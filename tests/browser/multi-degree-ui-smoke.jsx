import React, { act } from 'react';
import { createRoot } from 'react-dom/client';
import StudyPlaner from '../../study-planer';
import { initialDocument } from '../../multi-degree.mjs';
import { saveWorkspace, workspaceKey } from '../../planner-storage.mjs';
import '../../style.scss';
window.IS_REACT_ACT_ENVIRONMENT=true;
const store=new Map();
const storage={ getItem:key=>store.get(key)??null, setItem:(key,value)=>store.set(key,value) };
const prefix='ui:';
const doc=initialDocument();
doc.degrees[0].title='M.Sc. Informatik';
saveWorkspace(storage, workspaceKey(prefix,null), {document:doc,activeDegreeId:doc.degrees[0].id,dirty:false});
const options={storage,prefix,demoModules:[]};
const root=createRoot(document.getElementById('root'));
const assert=(condition,message)=>{if(!condition)throw new Error(message);};
const findButton=text=>[...document.querySelectorAll('button')].find(button=>button.textContent.trim()===text);
const click=async element=>{assert(element,'Missing button'); await act(async()=>element.click());};
const input=async(element,value)=>{assert(element,'Missing field');await act(async()=>{const setter=Object.getOwnPropertyDescriptor(element instanceof HTMLSelectElement?HTMLSelectElement.prototype:HTMLInputElement.prototype,'value').set;setter.call(element,value);element.dispatchEvent(new Event(element instanceof HTMLSelectElement?'change':'input',{bubbles:true}));});};
const submit=async form=>act(async()=>form.requestSubmit());
const tick=async()=>act(async()=>new Promise(resolve=>requestAnimationFrame(resolve)));
try {
 await act(async()=>root.render(<StudyPlaner plannerOptions={options}/>));
 await click(findButton('+ Studiengang'));
 let dialog=document.querySelector('dialog[open]'); assert(dialog,'No degree dialog');
 assert(document.activeElement===dialog.querySelector('input'),'Name field not focused');
 await input(dialog.querySelector('input'),'B.Sc. Mathematik mit einem sehr langen Studiengangnamen');
 await input(dialog.querySelector('select'),'bachelor');
 assert(dialog.querySelectorAll('input')[1].value==='180','Bachelor default not applied');
 await submit(dialog.querySelector('form')); assert(!document.querySelector('dialog[open]'),'Create dialog did not close');
 assert(document.querySelector('h1').textContent.includes('B.Sc.'),'New degree not selected');
 assert(document.querySelector('.fraction').textContent.includes('180'),'Wrong ECTS');
 await click(document.querySelector('.add-module-btn'));
 // Semester columns use an icon button with the Add module title.
 if(!document.querySelector('dialog[open]')) throw new Error('Module dialog not open');
 dialog=document.querySelector('dialog[open]');
 await input(dialog.querySelector('#module-name'),'Lineare Algebra');
 await input(dialog.querySelector('[aria-label="Studiengang im Modulformular"]'),doc.degrees[0].id);
 assert([...document.querySelectorAll('dialog[open]')].length===2,'No draft choice');
 await click(findButton('Abbrechen')); assert(document.querySelector('#module-name').value==='Lineare Algebra','Cancel lost draft');
 await input(document.querySelector('[aria-label="Studiengang im Modulformular"]'),doc.degrees[0].id);
 await click(findButton('Speichern und wechseln')); await tick();
 assert(document.querySelector('h1').textContent==='M.Sc. Informatik','Save and switch did not switch');
 assert(document.querySelectorAll('.module-card').length===0,'Saved module leaked into original degree');
 const switcher=document.getElementById('degree-switcher');
 const second=[...switcher.options].find(option=>option.value!==doc.degrees[0].id).value;
 await input(switcher,second); assert(document.querySelector('.module-card h4')?.textContent==='Lineare Algebra','Draft not saved in its own degree');
 await click(document.querySelector('.add-note-btn')); const note=document.querySelector('.notes-body textarea');
 await act(async()=>{const setter=Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype,'value').set;setter.call(note,'Exam notes');note.dispatchEvent(new Event('input',{bubbles:true}));});
 // Exercise the existing drag/drop path with the new ID-backed state.
 await click(document.querySelector('.add-semester-card'));
 const transfer=new DataTransfer();
 await act(async()=>document.querySelector('.module-card').dispatchEvent(new DragEvent('dragstart',{bubbles:true,dataTransfer:transfer})));
 const columns=[...document.querySelectorAll('.semester-col:not(button)')];
 await act(async()=>columns[columns.length-1].querySelector('.end-zone').dispatchEvent(new DragEvent('drop',{bubbles:true,dataTransfer:transfer})));
 assert(columns[columns.length-1].querySelector('.module-card h4')?.textContent==='Lineare Algebra','Drag/drop did not persist the new semester');
 const creditsEditor=document.querySelector('.requirement-credits-edit.inline-edit-display');
 await act(async()=>creditsEditor.dispatchEvent(new MouseEvent('dblclick',{bubbles:true})));
 await input(document.querySelector('.requirement-credits-edit.inline-edit-input'),'200');
 await act(async()=>document.querySelector('.requirement-credits-edit.inline-edit-input').dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true})));
 assert(document.querySelector('.fraction').textContent.includes('200'),'Requirement >30 ECTS was rejected');
 await click(findButton('Alle Studiengänge')); assert(document.querySelectorAll('.degree-overview-card').length===2,'Overview missing degree');
 assert(document.querySelector('.degree-summary').textContent.includes('320'),'Wrong combined ECTS');
 await click(document.querySelector('.degree-overview-card .secondary-btn'));
 await click(findButton('Verwalten')); dialog=document.querySelector('dialog[open]');
 await input(dialog.querySelector('input'),'M.Sc. Informatik – aktualisiert'); await submit(dialog.querySelector('form'));
 assert(document.querySelector('h1').textContent.includes('aktualisiert'),'Rename did not apply');
 await click(findButton('◐ Appearance')); await click(findButton('Porcelain')); await tick();
 assert(document.documentElement.dataset.palette==='porcelain','Light theme did not apply');
 assert(document.documentElement.scrollWidth<=innerWidth+1,'Horizontal page overflow at '+innerWidth+' px');
 await click(findButton('Alle Studiengänge')); await tick();
 assert(document.documentElement.scrollWidth<=innerWidth+1,'Overview overflows');
 document.getElementById('ui-result').textContent=`PASS — UI at ${innerWidth}px: create, defaults, drafts, switch, notes, overview, rename, drag/drop, ECTS editing, light theme and no overflow`;
} catch(error){document.getElementById('ui-result').textContent=`FAIL — ${error.stack}`;console.error(error);}
finally{window.IS_REACT_ACT_ENVIRONMENT=false;parent.postMessage({type:'ui-test-result',result:document.getElementById('ui-result').textContent},location.origin);}
